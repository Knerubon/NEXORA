# ---- schema generation ------------------------------------------------------------------------
def _kind_schema(kind: str) -> dict[str, Any]:
    if kind.startswith("enum:"):
        return {"enum": list(ENUMS[kind[5:]])}
    if kind == "ref":
        return {"$ref": "#/$defs/kind_ref"}
    return dict(KINDS[kind])


def _leaf(kind: str) -> dict[str, Any]:
    return {"anyOf": [{"const": NOT_VERIFIED}, _kind_schema(kind)]}


def _verified(kind: str) -> dict[str, Any]:
    return {"allOf": [{"not": {"const": NOT_VERIFIED}}, _kind_schema(kind)]}


def _obj(fields: Mapping[str, str], leaf: Any) -> dict[str, Any]:
    return {
        "type": "object",
        "additionalProperties": False,
        "required": list(fields),
        "properties": {k: leaf(v) for k, v in fields.items()},
    }


def _case(n: str, leaf: Any, result: Any) -> dict[str, Any]:
    return {
        "type": "object",
        "additionalProperties": False,
        "required": ["result", "evidence", "evidence_refs", "notes"],
        "properties": {
            "result": result,
            "evidence": _obj(CASE_FIELDS[n], leaf),
            "evidence_refs": (
                {"anyOf": [{"const": NOT_VERIFIED}, {"$ref": "#/$defs/kind_ref_list"}]}
                if leaf is _leaf
                else {"$ref": "#/$defs/kind_ref_list"}
            ),
            "notes": {"type": "string"},
        },
    }


def build_schema() -> dict[str, Any]:
    """The committed evidence-record.schema.json must equal this (drift test)."""
    claims = {"enum": list(MANDATORY_NOT_VERIFIED)}
    pass_props: dict[str, Any] = {k: _obj(v, _verified) for k, v in SECTIONS.items()}
    pass_props["checkout"]["properties"]["checkout_clean"] = {"const": True}
    pass_props["checkout"]["properties"]["head_equals_sha"] = {"const": True}
    pass_props["checkout"]["properties"]["status_short"] = {"const": ""}
    pass_props["dataset"]["properties"]["development_status"] = {"const": "TRUSTED"}
    pass_props["custody"]["properties"]["verifier_status"] = {"const": "TRUSTED"}
    pass_props["custody"]["properties"]["verifier_exit_code"] = {"const": 0}
    pass_props["custody"]["properties"]["revocations_after_approval"] = {"const": 0}
    pass_props["evidence_class"] = {"const": "REAL_WINDOWS_RUN"}
    pass_cases: dict[str, Any] = {}
    for n in CASE_FIELDS:
        c = _case(n, _verified, {"const": "PASS"})
        for key, value in CASE_PASS_REQUIRES.get(n, {}).items():
            c["properties"]["evidence"]["properties"][key] = {"const": value}
        pass_cases[n] = c
    pass_props["cases"] = {"properties": pass_cases}
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": SCHEMA_VERSION,
        "title": "Market-history Windows readiness evidence record",
        "description": (
            "GENERATED from tests/windows_integration_readiness/evidence_validator.py "
            "(build_schema). Structural gate only: evidence_validator.validate_record is "
            "authoritative and adds identity, checkout and overall-result derivation rules. "
            "Passing either proves nothing about Windows or MT5."
        ),
        "type": "object",
        "additionalProperties": False,
        "required": list(TOP_LEVEL),
        "$defs": {
            "kind_ref": KINDS["ref"],
            "kind_ref_list": {
                "type": "array",
                "minItems": 1,
                "items": {"$ref": "#/$defs/kind_ref"},
            },
        },
        "properties": {
            "schema_version": {"const": SCHEMA_VERSION},
            "evidence_class": {"enum": list(EVIDENCE_CLASSES)},
            "identity_basis": {"const": IDENTITY_BASIS},
            **{k: _obj(v, _leaf) for k, v in SECTIONS.items()},
            "cases": {
                "type": "object",
                "additionalProperties": False,
                "required": list(CASE_FIELDS),
                "properties": {n: _case(n, _leaf, {"enum": list(RESULTS)}) for n in CASE_FIELDS},
            },
            "overall_result": {"enum": list(RESULTS)},
            "not_verified": {"type": "array", "uniqueItems": True, "items": claims},
            "claim_evidence": {
                "type": "object",
                "propertyNames": claims,
                "additionalProperties": {"$ref": "#/$defs/kind_ref"},
            },
        },
        "allOf": [
            {
                "if": {"properties": {"overall_result": {"const": "PASS"}}},
                "then": {"properties": pass_props},
            },
            {
                "if": {"properties": {"evidence_class": {"const": "TEMPLATE"}}},
                "then": {"properties": {"overall_result": {"const": "NOT_RUN"}}},
            },
        ],
    }


# ---- authoritative validation -----------------------------------------------------------------
@dataclass
class Report:
    errors: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    derived_overall: str = "NOT_RUN"

    @property
    def ok(self) -> bool:
        return not self.errors

    def as_json(self) -> dict[str, Any]:
        return {
            "structurally_valid": self.ok,
            "errors": self.errors,
            "notes": self.notes,
            "derived_overall_result": self.derived_overall,
            "windows_verified": False,  # never: this tool checks structure, not Windows
            "identity_authenticated": False,  # never: identities are declared strings
        }


def _re(pattern: str, value: Any) -> bool:
    return isinstance(value, str) and re.search(pattern, value) is not None


def _is_int(v: Any) -> bool:
    return type(v) is int


def _kind_ok(kind: str, v: Any) -> bool:
    if kind.startswith("enum:"):
        return v in ENUMS[kind[5:]]
    checks: dict[str, Any] = {
        "text": lambda x: _re(_NONBLANK, x),
        "sha40": lambda x: _re(_SHA40, x),
        "sha256": lambda x: _re(_SHA256, x),
        "head_pin": lambda x: _re(_HEAD_PIN, x),
        "utc_ts": lambda x: _re(_UTC, x) and _parses(x),
        "bool": lambda x: type(x) is bool,
        "int": _is_int,
        "git_status": lambda x: isinstance(x, str),
        "text_list": lambda x: (
            isinstance(x, list) and bool(x) and all(_re(_NONBLANK, i) for i in x)
        ),
        "int_list": lambda x: isinstance(x, list) and bool(x) and all(_is_int(i) for i in x),
        "reason_list": lambda x: isinstance(x, list) and all(_re(_NONBLANK, i) for i in x),
        "int_pair": lambda x: (
            isinstance(x, list) and len(x) == 2 and all(_is_int(i) for i in x) and x[0] < x[1]
        ),
        "ref": _ref_ok,
        "ref_list": lambda x: isinstance(x, list) and bool(x) and all(_ref_ok(i) for i in x),
        "json": lambda x: isinstance(x, (dict, list)) and bool(x),
    }
    return bool(checks[kind](v))


def _ref_ok(v: Any) -> bool:
    return (
        isinstance(v, dict)
        and set(v) == {"path", "sha256"}
        and _re(_NONBLANK, v["path"])
        and _re(_SHA256, v["sha256"])
    )


def _parses(text: str) -> bool:
    try:
        datetime.fromisoformat(text.replace("Z", "+00:00"))
    except ValueError:
        return False
    return True


def normalize_identity(identity: str) -> str:
    """Same normalization idea as the V4 custody code (NFKC, trim, case-fold, collapse spaces),
    restated here so a disguised duplicate (case, spacing, compatibility characters) is caught.
    It cannot tell that two different names denote one human."""
    return " ".join(unicodedata.normalize("NFKC", identity).split()).casefold()


def _check_fields(
    obj: Any, fields: Mapping[str, str], path: str, r: Report, unresolved: list[str]
) -> dict[str, Any]:
    if not isinstance(obj, dict):
        r.errors.append(f"section_not_object:{path}")
        return {}
    for k in sorted(set(obj) - set(fields)):
        r.errors.append(f"unknown_field:{path}.{k}")
    for k in fields:
        if k not in obj:
            r.errors.append(f"missing_field:{path}.{k}")
    out: dict[str, Any] = {}
    for k, kind in fields.items():
        if k not in obj:
            unresolved.append(f"{path}.{k}")
            continue
        v = obj[k]
        if v == NOT_VERIFIED:
            unresolved.append(f"{path}.{k}")
        elif not _kind_ok(kind, v):
            r.errors.append(f"invalid_value:{path}.{k}:{kind}")
            unresolved.append(f"{path}.{k}")
        else:
            out[k] = v
    return out


def validate_record(record: Any) -> Report:
    r = Report()
    if not isinstance(record, dict):
        r.errors.append("record_not_object")
        return r
    for k in sorted(set(record) - set(TOP_LEVEL)):
        r.errors.append(f"unknown_field:{k}")
    for k in TOP_LEVEL:
        if k not in record:
            r.errors.append(f"missing_field:{k}")
    if record.get("schema_version") != SCHEMA_VERSION:
        r.errors.append("schema_version_mismatch")
    cls = record.get("evidence_class")
    if cls not in EVIDENCE_CLASSES:
        r.errors.append("unknown_evidence_class")
    if record.get("identity_basis") != IDENTITY_BASIS:
        r.errors.append("identity_basis_must_be_declared_not_authenticated")

    unresolved: list[str] = []
    v = {s: _check_fields(record.get(s), f, s, r, unresolved) for s, f in SECTIONS.items()}

    # cases
    cases = record.get("cases")
    results: dict[str, str] = {}
    if not isinstance(cases, dict) or set(cases) != set(CASE_FIELDS):
        r.errors.append("cases_must_be_exactly_1_to_7")
        cases = cases if isinstance(cases, dict) else {}
    for n, fields in CASE_FIELDS.items():
        c = cases.get(n)
        if not isinstance(c, dict) or set(c) != {"result", "evidence", "evidence_refs", "notes"}:
            r.errors.append(f"case_malformed:{n}")
            results[n] = "FAIL"
            continue
        res = c["result"]
        if res not in RESULTS:
            r.errors.append(f"unknown_case_result:{n}")
            res = "FAIL"
        results[n] = res
        if not isinstance(c["notes"], str):
            r.errors.append(f"case_notes_not_text:{n}")
        case_unresolved: list[str] = []
        ev = _check_fields(c["evidence"], fields, f"cases.{n}.evidence", r, case_unresolved)
        refs = c["evidence_refs"]
        refs_ok = _kind_ok("ref_list", refs)
        if refs != NOT_VERIFIED and not refs_ok:
            r.errors.append(f"invalid_value:cases.{n}.evidence_refs:ref_list")
        if res == "PASS":
            for path in case_unresolved:
                r.errors.append(f"pass_with_unverified_field:{path}")
            if not refs_ok:
                r.errors.append(f"pass_without_evidence_refs:case{n}")
            for key, want in CASE_PASS_REQUIRES.get(n, {}).items():
                if key in ev and ev[key] != want:
                    r.errors.append(f"pass_contradicted_by_evidence:cases.{n}.evidence.{key}")
        unresolved += case_unresolved

    # checkout cleanliness is derived from the recorded evidence, never trusted as a flag
    co, ident = v["checkout"], v["identity"]
    if "status_short" in co and "checkout_clean" in co:
        if co["checkout_clean"] != (co["status_short"].strip() == ""):
            r.errors.append("checkout_clean_contradicts_status_short")
    if {"head", "head_equals_sha"} <= set(co) and "extractor_sha" in ident:
        if co["head_equals_sha"] != (co["head"] == ident["extractor_sha"]):
            r.errors.append("head_equals_sha_contradicts_recorded_head")

    # people: declared identities must be pairwise distinct where independence is required
    ppl = v["people"]
    independent = ("operator", "second_person_verifier", "custodian")
    for i, a in enumerate(independent):
        for b in (*independent[i + 1 :], "reviewer"):
            if a in ppl and b in ppl and normalize_identity(ppl[a]) == normalize_identity(ppl[b]):
                r.errors.append(f"same_identity:{a}={b}")

    # dataset status may never claim more than the independent verifier observed
    ds, cu = v["dataset"], v["custody"]
    if ds.get("development_status") == "TRUSTED" and cu.get("verifier_status") != "TRUSTED":
        r.errors.append("dataset_trusted_without_trusted_verifier_status")
    if cu.get("verifier_status") == "TRUSTED" and cu.get("verifier_exit_code") not in (0, None):
        r.errors.append("verifier_trusted_with_nonzero_exit")
    if cu.get("verifier_status") == "TRUSTED" and cu.get("verifier_status_reasons"):
        r.errors.append("verifier_trusted_with_reasons")

    # explicit non-claims
    nv, ce = record.get("not_verified"), record.get("claim_evidence")
    if not isinstance(nv, list) or not all(isinstance(x, str) for x in nv):
        r.errors.append("not_verified_not_a_list")
        nv = []
    if not isinstance(ce, dict):
        r.errors.append("claim_evidence_not_object")
        ce = {}
    if len(set(nv)) != len(nv):
        r.errors.append("not_verified_duplicates")
    for c in sorted(set(nv) - set(MANDATORY_NOT_VERIFIED)):
        r.errors.append(f"unknown_claim:{c}")
    for c in sorted(set(ce) - set(MANDATORY_NOT_VERIFIED)):
        r.errors.append(f"unknown_claim:{c}")
    for c in MANDATORY_NOT_VERIFIED:
        if c in nv and c in ce:
            r.errors.append(f"claim_both_unverified_and_evidenced:{c}")
        elif c not in nv and c not in ce:
            r.errors.append(f"claim_dropped_without_evidence:{c}")
        elif c in ce and not _ref_ok(ce[c]):
            r.errors.append(f"claim_evidence_invalid:{c}")

    # template: nothing filled in
    if cls == "TEMPLATE":
        filled = [p for s, f in SECTIONS.items() for p in v[s]]
        if filled or any(res != "NOT_RUN" for res in results.values()):
            r.errors.append("template_must_be_unfilled")
    if cls == "SYNTHETIC_FIXTURE":
        rid = ident.get("record_id", "")
        if not str(rid).startswith("SYNTHETIC-"):
            r.errors.append("synthetic_record_id_must_start_with_SYNTHETIC-")
        if ds.get("development_status") == "TRUSTED" or cu.get("verifier_status") == "TRUSTED":
            r.errors.append("synthetic_fixture_cannot_claim_trusted")

    # derive overall; never trust the input value
    if any(res == "FAIL" for res in results.values()):
        derived = "FAIL"
    elif all(res == "PASS" for res in results.values()) and cls != "REAL_WINDOWS_RUN":
        # A template or synthetic fixture is never a run: its case results exercise the rules,
        # they cannot add up to readiness.
        derived = "NOT_RUN"
        r.notes.append("non_real_evidence_class_derives_NOT_RUN")
    elif all(res == "PASS" for res in results.values()):
        derived = "PASS"
        pre: list[str] = []
        pre += [f"pass_with_unverified_field:{p}" for p in unresolved if not p.startswith("cases.")]
        if co.get("checkout_clean") is not True:
            pre.append("pass_requires_clean_checkout")
        if co.get("head_equals_sha") is not True:
            pre.append("pass_requires_head_equals_sha")
        if cu.get("verifier_status") != "TRUSTED" or cu.get("verifier_exit_code") != 0:
            pre.append("pass_requires_trusted_independent_verification")
        if cu.get("revocations_after_approval") != 0:
            pre.append("pass_requires_no_revocation_after_approval")
        if ds.get("development_status") != "TRUSTED":
            pre.append("pass_requires_dataset_trusted")
        if pre:
            r.errors += pre
            derived = "FAIL"
    else:
        derived = "NOT_RUN"
    r.derived_overall = derived
    claimed = record.get("overall_result")
    if claimed not in RESULTS:
        r.errors.append("unknown_overall_result")
    elif claimed != derived:
        r.errors.append(f"overall_result_not_derivable:claimed={claimed},derived={derived}")
    return r


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print("usage: python -m tests.windows_integration_readiness.evidence_validator REC.json")
        return 2
    try:
        record = json.loads(Path(argv[1]).read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print(json.dumps({"structurally_valid": False, "errors": [f"unreadable:{exc}"]}))
        return 2
    report = validate_record(record)
    print(json.dumps(report.as_json(), indent=2, sort_keys=True))
    return 0 if report.ok else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
