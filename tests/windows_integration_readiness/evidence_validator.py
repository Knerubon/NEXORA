def _check_custody(
    v: Mapping[str, dict[str, Any]], claimed: frozenset[str], r: Report
) -> cg.GateDecision | None:
    cu = v["custody"]
    if {"revocation_seqs", "approval_seq", "revocations_after_approval"} <= set(cu):
        later = sum(1 for s in cu["revocation_seqs"] if s > cu["approval_seq"])
        if later != cu["revocations_after_approval"]:
            r.errors.append("revocations_after_approval_contradicts_revocation_seqs")
    if {"approval_seq", "candidate_approval_seqs"} <= set(cu):
        if cu["approval_seq"] not in cu["candidate_approval_seqs"]:
            r.errors.append("approval_seq_not_among_candidate_approval_seqs")
    bundle = _custody_bundle(v, claimed)
    recorded = (cu.get("gate_outcome"), cu.get("gate_reasons"))
    if bundle is None:
        if recorded[0] is not None:
            r.errors.append("custody_gate_decision_not_reproducible:inputs_not_verified")
        return None
    decision = cg.trust_gate(bundle)
    r.gate = decision
    if recorded[0] is not None and (
        recorded[0] != decision.outcome or set(recorded[1] or ()) != set(decision.reasons)
    ):
        r.errors.append("custody_gate_decision_mismatch")
    return decision


def _check_claims(record: Mapping[str, Any], deps: Mapping[str, str], r: Report) -> frozenset[str]:
    nv, ce = record.get("not_verified"), record.get("claim_evidence")
    if not isinstance(nv, list) or not all(isinstance(x, str) for x in nv):
        r.errors.append("not_verified_not_a_list")
        nv = []
    if not isinstance(ce, dict):
        r.errors.append("claim_evidence_not_object")
        ce = {}
    if len(set(nv)) != len(nv):
        r.errors.append("not_verified_duplicates")
    for c in sorted(set(nv) - set(MANDATORY_NOT_VERIFIED)):
        r.errors.append(f"unknown_claim:{c}")
    for c in sorted(set(ce) - set(MANDATORY_NOT_VERIFIED)):
        r.errors.append(f"unknown_claim:{c}")
    for c in MANDATORY_NOT_VERIFIED:
        if c in nv and c in ce:
            r.errors.append(f"claim_both_unverified_and_evidenced:{c}")
        elif c not in nv and c not in ce:
            r.errors.append(f"claim_dropped_without_evidence:{c}")
        elif c in ce and not _ref_ok(ce[c]):
            r.errors.append(f"claim_evidence_invalid:{c}")
    # R3-1: a reference cannot prove a capability whose owner is unresolved or has no method
    for c in sorted(set(ce) & set(MANDATORY_NOT_VERIFIED)):
        owner = CLAIM_OWNER.get(c, NO_REVIEWED_METHOD)
        if owner == NO_REVIEWED_METHOD:
            r.errors.append(f"claim_has_no_reviewed_evidence_method:{c}")
        elif owner is not None and deps.get(owner) != RESOLVED:
            r.errors.append(f"claim_requires_unresolved_dependency:{owner}:{c}")
    return frozenset(c for c in ce if CLAIM_OWNER.get(c) == "DEP-02")


def has_mock_marker(text: object) -> bool:
    """True when `text` carries a mock/synthetic/fixture marker (see _MARKER_PREFIXES)."""
    if not isinstance(text, str):
        return False
    visible = ascii_lookalikes(strip_hidden(unicodedata.normalize("NFKC", text)))
    tokens = [t.casefold() for t in _MARKER_TOKEN.findall(visible)]
    if any(t.startswith(_MARKER_PREFIXES) for t in tokens):
        return True
    if any(a == "test" and b == "only" for a, b in zip(tokens, tokens[1:], strict=False)):
        return True
    joined = "".join(tokens)
    return "synthetic" in joined or "fixture" in joined or "testonly" in joined


def _check_real_markers(v: Mapping[str, dict[str, Any]], r: Report) -> None:
    for section, key in REAL_MARKER_FIELDS:
        value = v[section].get(key)
        if value is None:
            continue
        texts = value if isinstance(value, list) else [value]
        for text in texts:
            if has_mock_marker(text) or str(text) == ec.MOCK_SOURCE:
                r.errors.append(f"real_record_carries_mock_marker:{section}.{key}")
                break
    rid = v["identity"].get("record_id")
    if rid is not None and not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{7,127}", str(rid)):
        r.errors.append("real_record_id_malformed")  # positive check: ASCII id, >= 8 characters
    sha = v["identity"].get("extractor_sha")
    if sha is not None and not dp.head_matches_candidate(sha):
        r.errors.append(
            f"real_record_extractor_sha_not_pinned_pr96_candidate:{dp.classify_head(sha)}"
        )


def validate_record(
    record: Any, *, _test_only_dependencies: Mapping[str, str] | None = None
) -> Report:
    """Authoritative check. `_test_only_dependencies` lets a TEST pretend dependencies are
    resolved so the evidence rules can be seen on their own; the CLI never passes it and the
    report then says `dependency_source: test_override`."""
    r = Report()
    deps = dependency_status()
    if _test_only_dependencies is not None:
        deps = {**deps, **_test_only_dependencies}
        r.dependency_source = "test_override"
    r.dependencies = dict(deps)
    if not isinstance(record, dict):
        r.errors.append("record_not_object")
        return r
    for k in sorted(set(record) - set(TOP_LEVEL)):
        r.errors.append(f"unknown_field:{k}")
    for k in TOP_LEVEL:
        if k not in record:
            r.errors.append(f"missing_field:{k}")
    if record.get("schema_version") != SCHEMA_VERSION:
        r.errors.append("schema_version_mismatch")
    cls = record.get("evidence_class")
    if cls not in EVIDENCE_CLASSES:
        r.errors.append("unknown_evidence_class")
    if record.get("identity_basis") != IDENTITY_BASIS:
        r.errors.append("identity_basis_must_be_declared_not_authenticated")

    unresolved: list[str] = []
    v = {s: _check_fields(record.get(s), f, s, r, unresolved) for s, f in SECTIONS.items()}
    results, case_ev = _check_cases(record.get("cases"), r, unresolved, cls)
    _check_execution(v, r)

    # checkout cleanliness is derived from the recorded evidence, never trusted as a flag
    co, ident = v["checkout"], v["identity"]
    if "status_short" in co and "checkout_clean" in co:
        if co["checkout_clean"] != (co["status_short"].strip() == ""):
            r.errors.append("checkout_clean_contradicts_status_short")
    if {"head", "head_equals_sha"} <= set(co) and "extractor_sha" in ident:
        if co["head_equals_sha"] != (co["head"] == ident["extractor_sha"]):
            r.errors.append("head_equals_sha_contradicts_recorded_head")

    # people: declared identities must be pairwise distinct where independence is required
    ppl = v["people"]
    independent = ("operator", "second_person_verifier", "custodian")
    for i, a in enumerate(independent):
        for b in (*independent[i + 1 :], "reviewer"):
            if a in ppl and b in ppl and normalize_identity(ppl[a]) == normalize_identity(ppl[b]):
                r.errors.append(f"same_identity:{a}={b}")

    # dataset status may never claim more than the independent verifier observed
    ds, cu = v["dataset"], v["custody"]
    if ds.get("development_status") == "TRUSTED" and cu.get("verifier_status") != "TRUSTED":
        r.errors.append("dataset_trusted_without_trusted_verifier_status")
    if cu.get("verifier_status") == "TRUSTED" and cu.get("verifier_exit_code") not in (0, None):
        r.errors.append("verifier_trusted_with_nonzero_exit")
    if cu.get("verifier_status") == "TRUSTED" and cu.get("verifier_status_reasons"):
        r.errors.append("verifier_trusted_with_reasons")

    claimed = _check_claims(record, deps, r)
    _check_verifier_argv(v, r)
    gate = _check_custody(v, claimed, r)

    # template: nothing filled in
    if cls == "TEMPLATE":
        filled = [p for s, f in SECTIONS.items() for p in v[s]]
        if filled or any(res != "NOT_RUN" for res in results.values()):
            r.errors.append("template_must_be_unfilled")
    if cls == "SYNTHETIC_FIXTURE":
        rid = ident.get("record_id", "")
        if not str(rid).startswith("SYNTHETIC-"):
            r.errors.append("synthetic_record_id_must_start_with_SYNTHETIC-")
        if ds.get("development_status") == "TRUSTED" or cu.get("verifier_status") == "TRUSTED":
            r.errors.append("synthetic_fixture_cannot_claim_trusted")
    if cls == "REAL_WINDOWS_RUN":
        _check_real_markers(v, r)

    # derive overall; never trust the input value
    if any(res == "FAIL" for res in results.values()):
        derived = "FAIL"
    elif all(res == "PASS" for res in results.values()) and cls != "REAL_WINDOWS_RUN":
        # A template or synthetic fixture is never a run: its case results exercise the rules,
        # they cannot add up to readiness.
        derived = "NOT_RUN"
        r.notes.append("non_real_evidence_class_derives_NOT_RUN")
    elif all(res == "PASS" for res in results.values()):
        derived = _derive_real(v, unresolved, gate, deps, case_ev, r)
    else:
        derived = "NOT_RUN"
    r.derived_overall = derived
    if cls == "REAL_WINDOWS_RUN":
        r.real_readiness = derived if derived in ("PASS", "BLOCKED") else "FAIL"
        if derived == "NOT_RUN":
            r.real_readiness = "NOT_CLAIMED"
    claimed_overall = record.get("overall_result")
    if claimed_overall not in OVERALL_RESULTS:
        r.errors.append("unknown_overall_result")
    elif claimed_overall != derived:
        r.errors.append(f"overall_result_not_derivable:claimed={claimed_overall},derived={derived}")
        if claimed_overall == "PASS" and derived == "BLOCKED":
            for dep in REAL_READINESS_REQUIRES:
                if deps.get(dep) != RESOLVED:
                    r.errors.append(f"real_readiness_pass_while_dependency_blocked:{dep}")
    return r


def _derive_real(
    v: Mapping[str, dict[str, Any]],
    unresolved: list[str],
    gate: cg.GateDecision | None,
    deps: Mapping[str, str],
    case_ev: Mapping[str, Mapping[str, Any]],
    r: Report,
) -> str:
    co, cu, ds, ex = v["checkout"], v["custody"], v["dataset"], v["execution"]
    pre: list[str] = []
    pre += [f"pass_with_unverified_field:{p}" for p in unresolved if not p.startswith("cases.")]
    if co.get("checkout_clean") is not True:
        pre.append("pass_requires_clean_checkout")
    if co.get("head_equals_sha") is not True:
        pre.append("pass_requires_head_equals_sha")
    if cu.get("verifier_status") != "TRUSTED" or cu.get("verifier_exit_code") != 0:
        pre.append("pass_requires_trusted_independent_verification")
    if cu.get("revocations_after_approval") != 0 or cu.get("revocation_seqs"):
        pre.append("pass_requires_no_revocation_after_approval")
    if ds.get("development_status") != "TRUSTED":
        pre.append("pass_requires_dataset_trusted")
    if any(code != 0 for code in ex.get("exit_codes", ())):
        pre.append("pass_with_nonzero_exit_code")
    run_a = case_ev.get("5", {}).get("run_a_content_sha256")
    if run_a is not None and "content_sha256" in ds and run_a != ds["content_sha256"]:
        pre.append("pass_contradicted_by_evidence:cases.5.run_hash_differs_from_dataset")
    if gate is None:
        pre.append("pass_requires_custody_gate_decision")
    else:
        if gate.outcome == cg.STOP:
            pre.append("pass_contradicted_by_custody_gate:STOP")
        pre += [
            f"pass_contradicted_by_custody_gate:{x}"
            for x in gate.reasons
            if not _is_dependency_reason(x)
        ]
    if pre:
        r.errors += pre
        return "FAIL"
    blocked = [d for d in REAL_READINESS_REQUIRES if deps.get(d) != RESOLVED]
    # Outside a test override, any dependency block the gate still reports (for example
    # unauthenticated principals) keeps the record BLOCKED even if the flags were flipped.
    residual = [] if r.dependency_source == "test_override" or gate is None else list(gate.reasons)
    if blocked or residual:
        r.notes += [f"real_readiness_blocked_by:{d}" for d in blocked]
        r.notes += [f"real_readiness_blocked_by_gate:{x}" for x in residual]
        return "BLOCKED"
    return "PASS"


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print("usage: python -m tests.windows_integration_readiness.evidence_validator REC.json")
        return 2
    try:
        record = json.loads(Path(argv[1]).read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print(json.dumps({"structurally_valid": False, "errors": [f"unreadable:{exc}"]}))
        return 2
    report = validate_record(record)
    print(json.dumps(report.as_json(), indent=2, sort_keys=True))
    return 0 if report.ok else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
