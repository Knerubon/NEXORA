def _strings(v: Any) -> list[str]:
    """Every string key and string leaf inside a JSON value."""
    if isinstance(v, dict):
        return [k for k in v if isinstance(k, str)] + [x for i in v.values() for x in _strings(i)]
    if isinstance(v, list):
        return [x for i in v for x in _strings(i)]
    return [v] if isinstance(v, str) else []


def _check_cases(
    cases: Any, r: Report, unresolved: list[str], cls: Any = None
) -> tuple[dict[str, str], dict[str, dict[str, Any]]]:
    results: dict[str, str] = {}
    evidence: dict[str, dict[str, Any]] = {}
    if not isinstance(cases, dict) or set(cases) != set(CASE_FIELDS):
        r.errors.append("cases_must_be_exactly_1_to_7")
        cases = cases if isinstance(cases, dict) else {}
    for n, fields in CASE_FIELDS.items():
        c = cases.get(n)
        if not isinstance(c, dict) or set(c) != {"result", "evidence", "evidence_refs", "notes"}:
            r.errors.append(f"case_malformed:{n}")
            results[n] = "FAIL"
            evidence[n] = {}
            continue
        res = c["result"]
        if res not in RESULTS:
            r.errors.append(f"unknown_case_result:{n}")
            res = "FAIL"
        results[n] = res
        if not isinstance(c["notes"], str):
            r.errors.append(f"case_notes_not_text:{n}")
        case_unresolved: list[str] = []
        ev = _check_fields(c["evidence"], fields, f"cases.{n}.evidence", r, case_unresolved)
        evidence[n] = ev
        refs = c["evidence_refs"]
        refs_ok = _kind_ok("ref_list", refs)
        if refs != NOT_VERIFIED and not refs_ok:
            r.errors.append(f"invalid_value:cases.{n}.evidence_refs:ref_list")
        # N1: a summary flag must equal what it summarises, whatever the case result
        for flag, (a, b) in DERIVED_EQUALITY_FLAGS.get(n, {}).items():
            if {flag, a, b} <= set(ev) and ev[flag] != (ev[a] == ev[b]):
                r.errors.append(f"derived_flag_contradicts_evidence:cases.{n}.evidence.{flag}")
        r.self_declared_flags += [
            f"cases.{n}.evidence.{f}" for f in SELF_DECLARED.get(n, ()) if f in ev
        ]
        if n == "6":
            _check_case6(ev, res, cls, n, r)
        if n == "7":
            _check_case7(ev, res, n, r)
        if n == "5" and "variant_content_sha256" in ev:
            values = _leaves(ev["variant_content_sha256"])
            if not values or not all(_re(_SHA256, x) for x in values):
                r.errors.append("invalid_value:cases.5.evidence.variant_content_sha256:sha256_map")
        if res == "PASS":
            for path in case_unresolved:
                r.errors.append(f"pass_with_unverified_field:{path}")
            if not refs_ok:
                r.errors.append(f"pass_without_evidence_refs:case{n}")
            for key, want in CASE_PASS_REQUIRES.get(n, {}).items():
                if key in ev and ev[key] != want:
                    r.errors.append(f"pass_contradicted_by_evidence:cases.{n}.evidence.{key}")
            if n == "5":
                _case5_pass(ev, r)
        unresolved += case_unresolved
    return results, evidence


def _leaves(v: Any) -> list[Any]:
    if isinstance(v, dict):
        return [x for i in v.values() for x in _leaves(i)]
    if isinstance(v, list):
        return [x for i in v for x in _leaves(i)]
    return [v]


def _case5_pass(ev: Mapping[str, Any], r: Report) -> None:
    a, b = ev.get("run_a_content_sha256"), ev.get("run_b_content_sha256")
    if a is not None and b is not None and a != b:
        r.errors.append("pass_contradicted_by_evidence:cases.5.run_hashes_differ")
    if a is not None and "variant_content_sha256" in ev:
        if any(x != a for x in _leaves(ev["variant_content_sha256"])):
            r.errors.append("pass_contradicted_by_evidence:cases.5.variant_hash_differs")


def _check_execution(v: Mapping[str, dict[str, Any]], r: Report) -> None:
    ex, ts, win = v["execution"], v["timestamps"], v["window"]
    if {"commands_run", "exit_codes"} <= set(ex):
        if len(ex["commands_run"]) != len(ex["exit_codes"]):
            r.errors.append("execution_record_incomplete:commands_run_vs_exit_codes")
    if {"started_at_utc", "finished_at_utc"} <= set(ts):
        if _when(ts["finished_at_utc"]) < _when(ts["started_at_utc"]):
            r.errors.append("timestamps_out_of_order:finished_before_started")
    if "preregistered_at_utc" in win and "started_at_utc" in ts:
        if _when(win["preregistered_at_utc"]) > _when(ts["started_at_utc"]):
            r.errors.append("preregistered_after_run_started")


def _when(text: str) -> datetime:
    return datetime.fromisoformat(text.replace("Z", "+00:00"))


def _check_verifier_argv(v: Mapping[str, dict[str, Any]], r: Report) -> cg.VerifyInvocation | None:
    cu = v["custody"]
    if "verifier_argv" not in cu:
        return None
    inv = cg.parse_verify_argv(cu["verifier_argv"])
    for problem in (*inv.problems, *(f"unknown_flag:{u}" for u in inv.unknown)):
        r.errors.append(f"verifier_argv_invalid:{problem}")
    bindings = (
        ("--store", cu.get("store_ref")),
        ("--registry", (cu.get("registry_ref") or {}).get("path")),
        ("--store-head", cu.get("store_head")),
        ("--pin", (cu.get("pin_ref") or {}).get("path")),
    )
    for flag, recorded in bindings:
        if flag in inv.flags and recorded is not None and inv.flags[flag] != recorded:
            r.errors.append(f"verifier_argv_differs_from_record:{flag}")
    if cu.get("verifier_status") == "TRUSTED" and (inv.problems or inv.unknown):
        r.errors.append("verifier_trusted_without_reviewed_v4_invocation")
    return inv


