"""Offline, fail-closed validator for Windows readiness evidence records (B-M1; round 4 N1, N2,
R3-1, R3-4).

The field specification below is the single source for three artifacts that must agree:
`evidence-record.schema.json` (generated by `build_schema`, drift-checked by a test), the
EVIDENCE-TEMPLATE.md tables, and `validate_record`, which is AUTHORITATIVE. JSON Schema can express
the per-field shape and the PASS-implies-verified rules; it cannot express identity distinctness,
checkout evidence cross-checks or the derivation of `overall_result`, so a record is accepted only
when `validate_record` returns no errors.

What this validator proves: the record is structurally complete and internally consistent, and a
PASS is derived from the recorded conditions instead of being trusted as input. Round 4 adds:
summary flags are re-derived from the values they summarise (N1); real-half readiness is derived
from machine-checked dependency status, so a REAL record derives BLOCKED while DEP-01 or DEP-03 is
BLOCKED (N2); the custody section is re-run through `custody_gate.trust_gate` and the verifier
invocation is a structured argv checked against the reviewed V4 CLI, mock/synthetic markers are
refused in REAL records and guarantees owned by an unresolved dependency cannot be "evidenced"
(R3-1); placeholder spellings of NOT VERIFIED are refused after NFKC normalisation (R3-4).

V9 (V8 reviewer findings): `NOT VERIFIED` is accepted only as the WHOLE value of a field that is
still unfilled; nested inside a list, a reference path or a structured value it is a refusal, as
in the JSON Schema. Case 7 is checked against an ALLOW-list of MT5 names (`mt5_reference`): every
observed reference that is not exactly an allowed read call counts. Case 6 flags are derived from
the probe outcomes when the record carries them; flags with no underlying evidence in the record
(`self_declared_flags` in the report) stay the operator's attestation. Custody evidence follows the
PR #96 CANDIDATE named by `dependency-manifest.json` (signed pin, attestation, approval, lineage).

What it can NOT prove: that any recorded value is true, that a person is who they claim to be
(identities are DECLARED strings; no signature or key is verified here, only that the recorded
signature/key fields are present, well formed and consistent), or anything about
Windows/MT5. Its report therefore always carries `windows_verified: false`. Offline harness
consistency (`structurally_valid`) is reported separately from `real_readiness`.

Usage: python -m tests.windows_integration_readiness.evidence_validator <record.json>
Exit code 0 only when the record has no errors. No I/O beyond reading that file; imports only this
package's custody gate and execution-contract register (for dependency status).
"""

